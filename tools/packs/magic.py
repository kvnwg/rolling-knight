"""
Turns the spell effects picked from two pixel magic-effect packs into AnimSheets
(src/render/pixel/indexed.ts), for the knights' skills (src/render/spells.ts plays them).

    python3 -I tools/packs/magic.py <Foozle dir> <magic dir> src/render/packs/magic.ts [--contact sheet.png]

<Foozle dir> is Foozle's "Pixel Magic Effects" folder (Fire_Ball/, Explosion/, Portal/, ...: one 64 x 64
PNG per frame). <magic dir> is the "1 Magic" folder of Craftpix's free magic effects (one strip per
effect, 72 x 72 frames side by side). --contact also writes the frames as they ship, at 4x.

Frames are copied 1:1 (one pack pixel = one art pixel, never scaled). The only changes:
  - whole quarter turns (the fireball that flies to the right falls; the beam that shoots right rises),
  - palette swaps, where an effect below names them (the beam's orange flecks turn holy gold, the
    vortex the Arcanist's violet, the stone spike ice), and a one-pixel edge where one is named (the
    beam's, in that gold: flat white alone reads as a shape cut out of the screen rather than light),
  - only the part of a frame inside a box, where one is named (one spike of the two),
  - alpha quantized to 0/255 (both packs are all-or-nothing already),
  - each effect's frames cropped to the union of their opaque pixels, identical frames stored once.
The anchor is given in the pack's frame and carried through the turn and the crop. Only PNG files
are read from the packs, as data; nothing in them is executed.

Art: Foozle, "Pixel Magic Effects" (Foozle_2DE0001): CC0. Craftpix.net, free pixel magic effects:
Craftpix's license (https://craftpix.net/file-licenses/) lets it ship inside the game; it must not be
redistributed on its own.

Left out, on purpose (EFFECTS below are the picks):
  - Foozle's Rocks, Water and Wind: thrown shots that smash into a wall on their right, and no skill
    throws rocks, water or wind. Water Geyser: no skill is water (its rock base and jet would read as
    a fountain in any colors). Tornado: Whirlwind is a blade spin (vfx.ts draws it), and a tornado
    three knights tall would bury the Blade in it.
  - Craftpix's thorn sprigs (1, 1_2), tiny fire bolts and their burst (4, 4_1, 4_2), hearts (5),
    candle flame (6), grass line (8) and magenta splats (10): one or two flat colors each, and too
    small or too plain next to the game's art. Its violet "star burst" (2): eight small flat blades on
    a thin dark ring, a reticle more than magic. Its white smoke puff (9): one flat white, no shading
    (the game's own smoke reads better). Its diagonal beam (3_2): the straight one (3), turned
    upright, is the holy light; a diagonal would only fit strikes from a corner. Its icons and font:
    UI, not effects.
  - The third pack offered, Pixel VFX LITE (explosion_1, magic_1): generated by a script (its README
    says so); at 1:1 its explosion is noise-dithered mush and its shockwave a circle facing the screen,
    where the game's rings lie flat on the ground.
"""
