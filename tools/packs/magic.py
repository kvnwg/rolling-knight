def natural(p):
    return [int(t) if t.isdigit() else t for t in re.split(r'(\d+)', p.name)]


def load_frames(fx, roots):
    root = roots[fx.pack]
    if fx.pack == 'foozle':
        d = root / fx.src
        if not d.is_dir():
            raise SystemExit(f'{fx.name}: {d} not found')
        files = sorted((p for p in d.iterdir() if p.suffix.lower() == '.png' and p.is_file() and not p.is_symlink()), key=natural)
        frames = []
        for p in files:
            with Image.open(p, formats=['PNG']) as im:
                frames.append(im.convert('RGBA'))
    else:
        p = root / fx.src
        if not p.is_file() or p.is_symlink():
            raise SystemExit(f'{fx.name}: {p} not found')
        with Image.open(p, formats=['PNG']) as im:
            im = im.convert('RGBA')
            if im.size[1] != STRIP_FRAME or im.size[0] % STRIP_FRAME:
                raise SystemExit(f'{fx.name}: {p.name} is {im.size}, expected {STRIP_FRAME} px frames in a row')
            frames = [im.crop((i * STRIP_FRAME, 0, (i + 1) * STRIP_FRAME, STRIP_FRAME)) for i in range(im.size[0] // STRIP_FRAME)]
    if not frames or len({f.size for f in frames}) != 1:
        raise SystemExit(f'{fx.name}: no frames, or frames of different sizes')
    return frames


def turned(im, anchor, q):
    """`q` quarter turns clockwise of a frame, and where the anchor lands."""
    x, y = anchor
    for _ in range(q % 4):
        h = im.size[1]
        im = im.transpose(Image.Transpose.ROTATE_270)
        x, y = h - 1 - y, x
    return im, (x, y)


def lum(c):
    return 0.3 * c[0] + 0.59 * c[1] + 0.11 * c[2]


def hex_rgb(h):
    return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5))


def edged(g, W, H, color):
    """A one-pixel edge in `color` round the opaque pixels (side by side, not corner to corner), the
    grid grown a pixel each way to hold it."""
    W2, H2 = W + 2, H + 2
    out = [None] * (W2 * H2)
    for i, c in enumerate(g):
        if c is not None:
            out[(i // W + 1) * W2 + i % W + 1] = c
    edge = []
    for y in range(H2):
        for x in range(W2):
            if out[y * W2 + x] is not None:
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                nx, ny = x + dx, y + dy
                if 0 <= nx < W2 and 0 <= ny < H2 and out[ny * W2 + nx] is not None:
                    edge.append(y * W2 + x)
                    break
    for i in edge:
        out[i] = color
    return out, W2, H2


def build(fx, roots):
    frames = load_frames(fx, roots)
    total = len(frames)
    # Only the frames some animation plays ship, in the pack's order.
    keep = sorted({i for _, _, idx in fx.anims.values() for i in idx})
    if not keep or keep[0] < 0 or keep[-1] >= total:
        raise SystemExit(f'{fx.name}: animations use frames {keep}, the pack has 0..{total - 1}')
    swap = {hex_rgb(a): hex_rgb(b) for a, b in fx.recolor.items()}
    anchor = fx.anchor
    seen = set()
    grids = []
    for i in keep:
        frame = frames[i]
        if fx.box:
            # Only the part inside the box (the frame keeps its size, so the anchor still holds).
            part = Image.new('RGBA', frame.size, (0, 0, 0, 0))
            part.paste(frame.crop(fx.box), fx.box[:2])
            frame = part
        f, anchor = turned(frame, fx.anchor, fx.turn)
        W, H = f.size
        data = f.tobytes()
        g = []
        for j in range(0, W * H * 4, 4):
            if data[j + 3] < ALPHA_MIN:
                g.append(None)
            else:
                c = tuple(data[j:j + 3])
                seen.add(c)
                g.append(swap.get(c, c))
        if fx.edge:
            g, W, H = edged(g, W, H, hex_rgb(fx.edge))
            anchor = (anchor[0] + 1, anchor[1] + 1)
        grids.append(g)
    missing = [a for a in fx.recolor if hex_rgb(a) not in seen]
    if missing:
        raise SystemExit(f'{fx.name}: recolor names colors its frames do not use: {missing}')
    used = {c for g in grids for c in g if c is not None}
    x0, y0, x1, y1 = W, H, -1, -1
    for g in grids:
        for i, c in enumerate(g):
            if c is None:
                continue
            x, y = i % W, i // W
            x0, y0, x1, y1 = min(x0, x), min(y0, y), max(x1, x), max(y1, y)
    if x1 < 0:
        raise SystemExit(f'{fx.name}: no opaque pixels')
    x1 += 1
    y1 += 1
    pal = sorted(used, key=lambda c: (lum(c), c))
    if len(pal) > len(KEYS):
        raise SystemExit(f'{fx.name}: {len(pal)} colors, at most {len(KEYS)}')
    key = {c: KEYS[i] for i, c in enumerate(pal)}
    unique = {}
    frames_out = []
    # The pack's frame index -> the stored frame.
    order = {}
    for i, g in zip(keep, grids):
        rows = tuple(''.join('.' if g[y * W + x] is None else key[g[y * W + x]] for x in range(x0, x1)) for y in range(y0, y1))
        if rows not in unique:
            unique[rows] = len(frames_out)
            frames_out.append(rows)
        order[i] = unique[rows]
    return {
        'fx': fx,
        'total': total,
        'picked': len(keep),
        'w': x1 - x0,
        'h': y1 - y0,
        'anchor': (anchor[0] - x0, anchor[1] - y0),
        'pal': ['#%02x%02x%02x' % c for c in pal],
        'frames': frames_out,
        'order': order,
    }


def emit(sheets):
    names = [s['fx'].name for s in sheets]
    out = [
        "// Generated by tools/packs/magic.py from Foozle's Pixel Magic Effects and Craftpix's free magic effects. Do not edit by hand.",
        '// Art: Foozle (CC0); Craftpix.net (ships inside the game; do not redistribute it on its own).',
        "import type { AnimSheet, IndexedRows } from '../pixel/indexed';",
        '',
        'export type MagicName = ' + ' | '.join(f"'{n}'" for n in names) + ';',
        '',
        '/** Frames are stored as one template string each, a row per line, without the transparent pixels at the end of each row. */',
        'function rows(w: number, h: number, frame: string): IndexedRows {',
        "  const r = frame.split('\\n').slice(1, -1);",
        '  if (r.length !== h) throw new Error(`magic frame has ${r.length} rows, expected ${h}`);',
        "  return r.map((row) => row.padEnd(w, '.'));",
        '}',
        '',
        "function fx(s: Omit<AnimSheet, 'frames'> & { frames: readonly string[] }): AnimSheet {",
        '  return { ...s, frames: s.frames.map((f) => rows(s.w, s.h, f)) };',
        '}',
        '',
        '/**',
        ' * The skills\' spell effects (src/render/spells.ts), drawn 1:1 in art pixels. Each sheet\'s anims',
        ' * list its frames; the anchor is the point the effect is placed by (said for each).',
        ' */',
        'export const MAGIC_SHEETS: Readonly<Record<MagicName, AnimSheet>> = {',
    ]
    for s in sheets:
        fx = s['fx']
        src = f"Foozle's {fx.src.replace('_', ' ')}" if fx.pack == 'foozle' else f"Craftpix's {fx.src}"
        turn = {0: '', 1: ', turned a quarter clockwise', 2: ', turned upside down', 3: ', turned a quarter counter-clockwise'}[fx.turn % 4]
        out.append('  /**')
        out.append(f'   * {src} ({s["picked"]} of its {s["total"]} frames{turn}), {s["w"]} x {s["h"]}.')
        out.extend(f'   * {line}' for line in textwrap.wrap(fx.note, 100))
        out.append('   */')
        out.append(f'  {fx.name}: fx({{')
        out.append(f'    w: {s["w"]},')
        out.append(f'    h: {s["h"]},')
        out.append(f'    anchor: {{ x: {s["anchor"][0]}, y: {s["anchor"][1]} }},')
        out.append("    faces: 'right',")
        out.append('    pal: [' + ', '.join(f"'{c}'" for c in s['pal']) + '],')
        anims = ', '.join(
            f"{name}: {{ fps: {fps}, loop: {'true' if loop else 'false'}, frames: [{', '.join(str(s['order'][i]) for i in idx)}] }}"
            for name, (fps, loop, idx) in fx.anims.items()
        )
        out.append(f'    anims: {{ {anims} }},')
        out.append('    frames: [')
        for rows in s['frames']:
            out.append('`')
            out.extend(r.rstrip('.') for r in rows)
            out.append('`,')
        out.append('    ],')
        out.append('  }),')
    out += ['};', '']
    return '\n'.join(out)


def contact(sheets, path, scale=4):
    """Every frame each sheet keeps, in its anims' order, at `scale`, on a dark ground with a 16 px grid."""
    pad = 6
    label = 14
    rows = []
    for s in sheets:
        for name, (fps, loop, idx) in s['fx'].anims.items():
            rows.append((s, name, [s['order'][i] for i in idx], fps))
    width = max(len(fr) * (s['w'] * scale + pad) for s, _, fr, _ in rows) + pad
    height = sum(s['h'] * scale + label + pad for s, _, _, _ in rows) + pad
    im = Image.new('RGBA', (width, height), (30, 26, 36, 255))
    dr = ImageDraw.Draw(im)
    y = pad
    for s, name, fr, fps in rows:
        dr.text((pad, y), f"{s['fx'].name}.{name}  {s['w']} x {s['h']}  {fps} fps  (anchor {s['anchor'][0]}, {s['anchor'][1]})", fill=(220, 220, 230, 255))
        y += label
        x = pad
        pal = [hex_rgb(c) for c in s['pal']]
        for f in fr:
            dr.rectangle([x - 1, y - 1, x + s['w'] * scale, y + s['h'] * scale], outline=(60, 54, 70, 255))
            for ry, row in enumerate(s['frames'][f]):
                for rx, ch in enumerate(row):
                    if ch != '.':
                        c = pal[KEYS.index(ch)]
                        dr.rectangle([x + rx * scale, y + ry * scale, x + (rx + 1) * scale - 1, y + (ry + 1) * scale - 1], fill=c + (255,))
            ax, ay = s['anchor']
            dr.rectangle([x + ax * scale, y + ay * scale, x + ax * scale + scale - 1, y + ay * scale + scale - 1], outline=(255, 0, 255, 255))
            x += s['w'] * scale + pad
        y += s['h'] * scale + pad
    im.save(path)


def main():
    args = sys.argv[1:]
    sheet_png = None
    if '--contact' in args:
        i = args.index('--contact')
        sheet_png = Path(args[i + 1])
        args = args[:i] + args[i + 2:]
    if len(args) != 3:
        raise SystemExit(__doc__)
    roots = {'foozle': Path(args[0]), 'craftpix': Path(args[1])}
    out = Path(args[2])
    sheets = [build(fx, roots) for fx in EFFECTS]
    src = emit(sheets)
    out.write_text(src)
    for s in sheets:
        fx = s['fx']
        print(f"{fx.name:10s} {fx.pack:8s} {fx.src:14s} {len(s['frames']):2d} frames kept ({s['picked']} picked of {s['total']})  {s['w']:2d} x {s['h']:2d}  {len(s['pal']):2d} colors")
    print(f'{out}: {len(src.encode())} bytes')
    if sheet_png:
        contact(sheets, sheet_png)
        print(f'{sheet_png}: written')


if __name__ == '__main__':
    main()
