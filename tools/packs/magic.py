# Palette keys, as in src/render/pixel/indexed.ts (letters and digits only: safe in template strings).
KEYS = '0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ'
# Alpha at or above this is opaque; below it the pixel is dropped.
ALPHA_MIN = 128
# The Craftpix strips' frame size.
STRIP_FRAME = 72


class Fx:
    def __init__(self, name, pack, src, anims, anchor, turn=0, recolor=None, box=None, edge=None, note=''):
        self.name = name
        self.pack = pack  # 'foozle' (a folder of frames) or 'craftpix' (a strip)
        self.src = src  # the folder or the strip's file name
        self.anims = anims  # name -> (fps, loop, [the pack's frames, from 0]); only these frames ship
        self.anchor = anchor  # in the pack's frame, before the turn
        self.turn = turn  # quarter turns clockwise
        self.recolor = recolor or {}  # '#rrggbb' -> '#rrggbb'
        self.box = box  # (x0, y0, x1, y1) in the pack's frame: only what's inside is kept (None: all)
        self.edge = edge  # '#rrggbb': a one-pixel edge round the art in this color (None: none)
        self.note = note


