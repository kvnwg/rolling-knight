"""
Knight bodies from Snoblin's "Pixel RPG Prototype Characters" (the gray Default mannequin: 32 x 32
cells; rows face down, right and up; idle 2 frames, walk 4, hurt 2, death 3). Every pixel of every
frame gets a role and a shade so the game can dress the mannequin as each knight at runtime:

  k outline   e eye (the ink dots inside the face)
  h i j       head: dark, mid, light (the face shows under helmets; hair and helmets are drawn over it)
  t u v       torso      a b c   arms      l m n   legs      f g   feet

The head is the sprite's top 7 rows, the body the next 4 (arms are its outer columns), the legs the
rest. Each frame also records its head box and both hands, where helmets, shields and weapons go.

  python3 -I tools/packs/mannequin.py "<pack>/Characters/Prototype_Character/Default" src/render/packs/mannequin.ts
  python3 -I tools/packs/mannequin.py --preview "<same dir>" <out.png>
"""
import os
import sys
from PIL import Image

SHEETS = {'idle': 2, 'walk': 4, 'hurt': 2, 'death': 3}
VIEWS = ['down', 'side', 'up']
CELL = 32
SHADE = {(0x87, 0x76, 0x88): 0, (0x9b, 0x86, 0x9c): 1, (0xad, 0x99, 0xac): 2}
OUTLINE = (0x3d, 0x25, 0x3b)


def classify(cell, view, lying):
    px = cell.load()
    W, H = cell.size
    opaque = [(x, y) for y in range(H) for x in range(W) if px[x, y][3]]
    if not opaque:
        return None
    top = min(y for _, y in opaque)
    bottom = max(y for _, y in opaque)
    xs = [x for x, _ in opaque]
    cx = (min(xs) + max(xs)) / 2
    head_rows = range(top, top + 7)
    body_rows = range(top + 7, top + 11)
    head = [(x, y) for x, y in opaque if y in head_rows]
    hx0 = min(x for x, _ in head)
    hx1 = max(x for x, _ in head)
    rows = []
    for y in range(H):
        row = []
        for x in range(W):
            c = px[x, y]
            if not c[3]:
                row.append('.')
                continue
            rgb = c[:3]
            if rgb == OUTLINE:
                # Ink inside the face (not on its edge) is an eye.
                inner = y in range(top + 2, top + 6) and hx0 < x < hx1 and px[x - 1, y][3] and px[x + 1, y][3] and px[x - 1, y][:3] != OUTLINE and px[x + 1, y][:3] != OUTLINE
                row.append('e' if inner and view != 'up' and not lying else 'k')
                continue
            s = SHADE.get(rgb, 1)
            if lying:
                part = 'hij' if x >= cx else 'tuv'
            elif y in head_rows:
                part = 'hij'
            elif y in body_rows:
                part = 'tuv' if abs(x + 0.5 - (cx + 0.5)) <= (2.6 if view != 'side' else 1.6) else 'abc'
            elif y >= bottom:
                part = 'fg' + 'g'
            else:
                part = 'lmn'
            row.append(part[s])
        rows.append(''.join(row))
    arms = [(x, y) for y in body_rows for x in range(W) if rows[y][x] in 'abc']
    if arms:
        right = max(arms, key=lambda p: (p[0], p[1]))
        left = min(arms, key=lambda p: (p[0], -p[1]))
        hand_r = max((p for p in arms if p[0] >= right[0] - 1), key=lambda p: p[1])
        hand_l = max((p for p in arms if p[0] <= left[0] + 1), key=lambda p: p[1])
    else:
        hand_r = hand_l = (int(cx), top + 9)
    return {'rows': rows, 'top': top, 'head': (hx0, top, hx1, top + 6), 'handR': hand_r, 'handL': hand_l}


def build(d):
    frames = []
    anims = {}
    for name, n in SHEETS.items():
        im = Image.open(os.path.join(d, f'{name}.png')).convert('RGBA')
        for vi, view in enumerate(VIEWS):
            ids = []
            for f in range(n):
                cell = im.crop((f * CELL, vi * CELL, (f + 1) * CELL, (vi + 1) * CELL))
                lying = name == 'death' and f > 0
                fr = classify(cell, view, lying)
                if fr is None:
                    continue
                ids.append(len(frames))
                frames.append(fr)
            anims[f'{name}_{view}'] = ids
    return frames, anims


def crop_box(frames):
    x0 = min(r.find(next(ch for ch in r if ch != '.')) for f in frames for r in f['rows'] if r.strip('.'))
    x1 = max(len(r.rstrip('.')) for f in frames for r in f['rows'])
    y0 = min(f['top'] for f in frames)
    y1 = max(i for f in frames for i, r in enumerate(f['rows']) if r.strip('.')) + 1
    return x0, y0, x1, y1


def write_ts(frames, anims, out):
    x0, y0, x1, y1 = crop_box(frames)
    W, H = x1 - x0, y1 - y0
    L = [
        '/**',
        " * Knight bodies (generated by tools/packs/mannequin.py from Snoblin's Pixel RPG Prototype Characters,",
        ' * the gray Default mannequin; do not edit). Roles: k outline, e eye, h/i/j head, t/u/v torso, a/b/c',
        ' * arms, l/m/n legs, f/g feet (dark, mid, light). Side frames face right. Feet on the bottom row.',
        ' */',
        'export interface BodyFrame {',
        '  rows: readonly string[];',
        '  /** Head box (x0, y0, x1, y1), inclusive. */',
        '  head: readonly [number, number, number, number];',
        '  /** The right-hand and left-hand ends of the arms (as drawn). */',
        '  handR: readonly [number, number];',
        '  handL: readonly [number, number];',
        '}',
        '',
        f'export const BODY_W = {W};',
        f'export const BODY_H = {H};',
        f'/** Where the feet touch the ground, in frame pixels. */',
        f'export const BODY_ANCHOR = {{ x: {16 - x0}, y: {H - 1} }};',
        '',
        'export const BODY_FRAMES: readonly BodyFrame[] = [',
    ]
    for f in frames:
        rows = [r[x0:x1] for r in f['rows'][y0:y1]]
        hx0, hy0, hx1, hy1 = f['head']
        L.append('  {')
        L.append('    rows: [' + ', '.join(f"'{r}'" for r in rows) + '],')
        L.append(f'    head: [{hx0 - x0}, {hy0 - y0}, {hx1 - x0}, {hy1 - y0}],')
        L.append(f"    handR: [{f['handR'][0] - x0}, {f['handR'][1] - y0}],")
        L.append(f"    handL: [{f['handL'][0] - x0}, {f['handL'][1] - y0}],")
        L.append('  },')
    L.append('];')
    L.append('')
    L.append('/** Frame indexes per animation and view (idle, walk, hurt, death x down, side, up). */')
    L.append('export const BODY_ANIMS: Readonly<Record<string, readonly number[]>> = {')
    for k, v in anims.items():
        L.append(f"  {k}: [{', '.join(map(str, v))}],")
    L.append('};')
    L.append('')
    open(out, 'w').write('\n'.join(L))
    print(f'wrote {out}: {len(frames)} frames, {W}x{H}')


COLORS = {'k': (61, 37, 59), 'e': (255, 255, 255), 'h': (200, 150, 120), 'i': (230, 180, 150), 'j': (250, 210, 180),
          't': (120, 30, 30), 'u': (170, 50, 50), 'v': (220, 80, 80), 'a': (30, 60, 120), 'b': (50, 90, 170), 'c': (90, 140, 220),
          'l': (40, 90, 40), 'm': (60, 130, 60), 'n': (90, 170, 90), 'f': (60, 40, 20), 'g': (100, 70, 40)}


def preview(frames, out):
    n = len(frames)
    img = Image.new('RGBA', (CELL * 9, CELL * ((n + 8) // 9)), (60, 70, 60, 255))
    for i, f in enumerate(frames):
        ox, oy = (i % 9) * CELL, (i // 9) * CELL
        for y, r in enumerate(f['rows']):
            for x, ch in enumerate(r):
                if ch != '.':
                    img.putpixel((ox + x, oy + y), COLORS[ch] + (255,))
        img.putpixel((ox + f['handR'][0], oy + f['handR'][1]), (255, 255, 0, 255))
        img.putpixel((ox + f['handL'][0], oy + f['handL'][1]), (0, 255, 255, 255))
    img.resize((img.size[0] * 5, img.size[1] * 5), Image.NEAREST).save(out)


if __name__ == '__main__':
    if sys.argv[1] == '--preview':
        preview(build(sys.argv[2])[0], sys.argv[3])
    else:
        fr, an = build(sys.argv[1])
        write_ts(fr, an, sys.argv[2])
